const String kAvatarModelAsset = 'assets/models/agent.glb';
const String kAvatarIblAsset = 'assets/environments/default_env_ibl.ktx';

/// 3D avatar viewport with clean live status pill, photo/GLB support,
/// and interactive mini-laptop overlay when working.
class Avatar3DViewport extends StatefulWidget {
  final AgentActivity activity;
  final Widget fallback;
  final double size;

  /// Optional custom `.glb` path selected or generated by the user.
  final String? customGlbPath;

  /// Optional user photo path: when set, renders an animated 2.5D character
  /// rigged from the user's photo with the interactive mini-laptop prop.
  final String? customPhotoPath;

  /// Optional Gemini Vision-generated stylized character profile built from a user photo.
  final GeminiAvatarProfile? geminiProfile;

  /// Optional background color for the square avatar card.
  final Color? boxBackgroundColor;

  /// Called on long press, meant to confirm `/stop`.
  final VoidCallback? onLongPress;

  /// Called on tap when the avatar is idle and in fallback mode.
  final VoidCallback? onTapIdleFallback;

  const Avatar3DViewport({
    super.key,
    required this.activity,
    required this.fallback,
    this.size = 114,
    this.customGlbPath,
    this.customPhotoPath,
    this.geminiProfile,
    this.boxBackgroundColor,
    this.onLongPress,
    this.onTapIdleFallback,
  });

  @override
  State<Avatar3DViewport> createState() => _Avatar3DViewportState();
}

class _Avatar3DViewportState extends State<Avatar3DViewport> {
  final Avatar3DController _controller = Avatar3DController();
  ThermionViewer? _viewer;
  bool _ready = false;
  bool _showDetail = false;

  @override
  void initState() {
    super.initState();
    _controller.apply(widget.activity);
    unawaited(_init3D());
  }

  @override
  void didUpdateWidget(covariant Avatar3DViewport old) {
    super.didUpdateWidget(old);
    if (old.activity != widget.activity) {
      _controller.apply(widget.activity);
    }
    if (old.customGlbPath != widget.customGlbPath) {
      unawaited(_reload3D());
    }
  }

  Future<void> _reload3D() async {
    await _disposeViewer();
    if (mounted) setState(() => _ready = false);
    await _init3D();
  }

  Future<String?> _resolveGlbUri() async {
    final custom = widget.customGlbPath;
    if (custom != null && custom.isNotEmpty && File(custom).existsSync()) {
      return 'file://$custom';
    }
    try {
      await rootBundle.load(kAvatarModelAsset);
      return kAvatarModelAsset;
    } catch (_) {
      return null;
    }
  }

  Future<void> _init3D() async {
    final uri = await _resolveGlbUri();
    if (uri == null) return;
    try {
      final viewer = await ThermionFlutterPlugin.createViewer();
      _viewer = viewer;
      await viewer.setBackgroundColor(0, 0, 0, 0);
      await viewer.loadIbl(kAvatarIblAsset, intensity: 28000);
      await viewer.addDirectLight(DirectLight.sun(
        intensity: 70000,
        direction: vm.Vector3(-0.4, -1, -0.7),
        castShadows: true,
      ));
      await viewer.setShadowsEnabled(true);
      await viewer.setPostProcessing(true);
      final asset = await viewer.loadGltf(uri);
      await asset.transformToUnitCube();
      final camera = await viewer.getActiveCamera();
      await camera.lookAt(vm.Vector3(0, 0.05, 1.7), focus: vm.Vector3.zero());
      await viewer.setRendering(true);
      await _controller.attach(viewer, asset);
      if (mounted) setState(() => _ready = true);
    } catch (err) {
      debugPrint('Avatar3D: Filament init failed, using fallback: $err');
      await _disposeViewer();
    }
  }

  Future<void> _disposeViewer() async {
    _controller.detach();
    final v = _viewer;
    _viewer = null;
    if (v != null) await v.dispose();
  }

  void _onTap() {
    if (_controller.state == Avatar3DState.idle) {
      if (_controller.has3D) {
        unawaited(_controller.wave());
      } else {
        widget.onTapIdleFallback?.call();
      }
      return;
    }
    setState(() => _showDetail = !_showDetail);
  }

  @override
  void dispose() {
    unawaited(_disposeViewer());
    _controller.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final viewer = _viewer;
    final hasPhoto = widget.customPhotoPath != null &&
        widget.customPhotoPath!.isNotEmpty &&
        File(widget.customPhotoPath!).existsSync();

    return AnimatedBuilder(
      animation: _controller,
      builder: (context, _) {
        final act = _controller.activity;
        final showPill = act.state != Avatar3DState.idle && act.label.isNotEmpty;
        return Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            GestureDetector(
              behavior: HitTestBehavior.opaque,
              onTap: _onTap,
              onLongPress: widget.onLongPress,
              onHorizontalDragStart: (_) => _controller.dragStart(),
              onHorizontalDragUpdate: (d) => _controller.dragUpdate(d.delta.dx),
              onHorizontalDragEnd: (_) => _controller.dragEnd(),
              child: SizedBox(
                width: widget.size,
                height: widget.size * 0.92,
                child: Stack(
                  alignment: Alignment.center,
                  children: [
                    Positioned(
                      bottom: 2,
                      child: Container(
                        width: widget.size * 0.48,
                        height: widget.size * 0.06,
                        decoration: BoxDecoration(
                          borderRadius: BorderRadius.circular(widget.size),
                          gradient: RadialGradient(colors: [
                            Colors.black.withValues(alpha: 0.45),
                            Colors.black.withValues(alpha: 0),
                          ]),
                        ),
                      ),
                    ),
                    if (_ready && viewer != null)
                      Positioned.fill(child: ThermionWidget(viewer: viewer))
                    else if (widget.geminiProfile != null)
                      Positioned.fill(
                        child: GeminiCharacterAvatar(
                          profile: widget.geminiProfile!,
                          state: act.state,
                          boxBackgroundColor: widget.boxBackgroundColor,
                        ),
                      )
                    else if (hasPhoto)
                      Positioned.fill(
                        child: PhotoCharacterAvatar(
                          photoPath: widget.customPhotoPath!,
                          state: act.state,
                        ),
                      )
                    else
                      Positioned.fill(child: widget.fallback),
                    Positioned.fill(
                      child: IgnorePointer(
                        child: WorkingPropOverlay(state: act.state),
                      ),
                    ),
                  ],
                ),
              ),
            ),
            AnimatedSize(
              duration: const Duration(milliseconds: 180),
              curve: Curves.easeOutCubic,
              child: showPill
                  ? Padding(
                      padding: const EdgeInsets.only(top: 6),
                      child: CleanStatusPill(activity: act),
                    )
                  : const SizedBox.shrink(),
            ),
            if (_showDetail && act.detail.isNotEmpty && act.state != Avatar3DState.idle)
              Padding(
                padding: const EdgeInsets.only(top: 6),
                child: AvatarDetailCard(detail: act.detail),
              ),
          ],
        );
      },
    );
  }
}
